"""The canonical transition monoid S_p of a finite predictive machine.

In Project B this is a covariate only.  Elements are tuples over the live
states plus one dead state (the last index), acting on the right: the element
of a word w sends state i to the state reached by reading w from i.
"""

from __future__ import annotations

from dataclasses import dataclass

from .ghmm import PredictiveMachine


@dataclass(frozen=True)
class MonoidSummary:
    size: int
    aperiodic: bool
    max_period: int  # largest cyclic group generated by a single element
    max_live_rank: int


def generators(pm: PredictiveMachine) -> list[tuple]:
    assert pm.complete, "the predictive machine was truncated"
    dead = len(pm)
    k = len(pm.step[0])
    return [
        tuple(dead if row[o] is None else row[o] for row in pm.step) + (dead,)
        for o in range(k)
    ]


def elements(pm: PredictiveMachine, max_size: int = 200_000) -> dict:
    """All elements of S_p, each mapped to a shortest word producing it."""
    gens = generators(pm)
    ident = tuple(range(len(pm) + 1))
    words = {ident: ()}
    queue = [ident]
    while queue:
        t = queue.pop(0)
        for o, g in enumerate(gens):
            nxt = tuple(g[i] for i in t)
            if nxt not in words:
                if len(words) >= max_size:
                    raise ValueError("monoid exceeds max_size")
                words[nxt] = words[t] + (o,)
                queue.append(nxt)
    return words


def _period(t: tuple) -> int:
    """Length of the cycle that the powers of t eventually enter."""
    seen = {}
    cur, i = t, 0
    while cur not in seen:
        seen[cur] = i
        cur = tuple(t[j] for j in cur)
        i += 1
    return i - seen[cur]


def summarise(pm: PredictiveMachine) -> MonoidSummary:
    els = elements(pm)
    dead = len(pm)
    periods = [_period(t) for t in els]
    live_rank = max(len(set(t[:dead]) - {dead}) for t in els)
    return MonoidSummary(len(els), max(periods) == 1, max(periods), live_rank)
