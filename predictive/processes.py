"""Named processes.  All exact, all small."""

from __future__ import annotations

from fractions import Fraction as Fr
from typing import Optional, Sequence

from .ghmm import GHMM, hmm_from_edges, markov_chain

H = Fr(1, 2)


def iid(probs: Sequence = (H, H)) -> GHMM:
    """Independent symbols.  One predictive state: the trivially easy control."""
    return hmm_from_edges("iid", 1, len(probs), [(0, o, 0, p) for o, p in enumerate(probs)])


def z1r() -> GHMM:
    """Zero, one, random: emits 0, then 1, then a fair coin, repeatedly."""
    edges = [(0, 0, 1, 1), (1, 1, 2, 1), (2, 0, 0, H), (2, 1, 0, H)]
    return hmm_from_edges("z1r", 3, 2, edges)


def rrxor() -> GHMM:
    """Random, random, xor: two fair coins and then their exclusive-or."""
    S, A0, A1, B0, B1 = range(5)
    edges = [
        (S, 0, A0, H), (S, 1, A1, H),
        (A0, 0, B0, H), (A0, 1, B1, H),
        (A1, 0, B1, H), (A1, 1, B0, H),
        (B0, 0, S, 1), (B1, 1, S, 1),
    ]
    return hmm_from_edges("rrxor", 5, 2, edges)


def reset_chain() -> GHMM:
    """The three-symbol full-support Markov chain of the paper's reset example."""
    P = [[Fr(1, 2), Fr(1, 3), Fr(1, 6)],
         [Fr(1, 3), Fr(1, 6), Fr(1, 2)],
         [Fr(1, 6), Fr(1, 2), Fr(1, 3)]]
    return markov_chain("reset_chain", P)


def square_chain() -> GHMM:
    """A four-symbol Markov chain with Hankel rank 3 and minimal HMM dimension 4.

    The transition matrix is half the 0/1 matrix whose rows are
    (1,1,0,0), (1,0,1,0), (0,1,0,1), (0,0,1,1).  Row 1 + row 4 = row 2 + row 3,
    so the rank is 3, but the support pattern has a fooling set of size 4, so
    no three-state HMM generates the process.
    """
    M = [[1, 1, 0, 0], [1, 0, 1, 0], [0, 1, 0, 1], [0, 0, 1, 1]]
    P = [[Fr(x, 2) for x in row] for row in M]
    return markov_chain("square_chain", P)


def mod_counter(m: int, k: Optional[int] = None, bias: Fr = Fr(1)) -> GHMM:
    """Hidden state in Z_m, started at 0, advanced by each emitted symbol.

    The state after a history is the sum of its symbols modulo m, so the
    next-symbol law depends on the whole context: there is no synchronising
    suffix.  In state s the symbol s mod k has weight 1 + bias and every other
    symbol weight 1.  With k = m this is modular addition of the context,
    read out as a distribution.
    """
    k = m if k is None else k
    edges = []
    for s in range(m):
        w = [Fr(1) + (bias if o == s % k else 0) for o in range(k)]
        z = sum(w)
        edges += [(s, o, (s + o) % m, w[o] / z) for o in range(k)]
    return hmm_from_edges(f"mod_counter_{m}_{k}", m, k, edges, init=[1] + [0] * (m - 1))


def twisted_square(m: int = 3, generic: bool = False) -> GHMM:
    """The square chain twisted by a hidden mod-m counter: d = 3m, n = 4m.

    Alphabet {0,1,2,3}.  The hidden state is (s, c): s is the last symbol and
    c in Z_m is the sum of all emitted symbols modulo m.  From (s, c) the next
    symbol is drawn from row s of

        [[x, 1-x, 0, 0], [y, 0, 1-y, 0], [0, 1-y, 0, y], [0, 0, 1-x, x]]

    with x = (c+1)/(m+1).  In the twisted process y = x, so row 0 + row 3 =
    row 1 + row 2 for every c and the Hankel rank drops to 3m, while the zero
    pattern still forces 4m hidden states (see `block_fooling_bound`).  The
    next-symbol law depends on the counter, so on the whole context.

    With `generic` True, y = (c+1)/(m+2) instead.  The support, alphabet,
    hidden states and contexts are unchanged but the row identity fails, so
    d = n = 4m: a matched control differing only in d.
    """
    idx = lambda s, c: s * m + c
    edges = []
    for c in range(m):
        x = Fr(c + 1, m + 1)
        y = Fr(c + 1, m + 2) if generic else x
        rows = [{0: x, 1: 1 - x}, {0: y, 2: 1 - y}, {1: 1 - y, 3: y}, {2: 1 - x, 3: x}]
        for s in range(4):
            for a, pr in rows[s].items():
                edges.append((idx(s, c), a, idx(a, (c + a) % m), pr))
    init = [Fr(0)] * (4 * m)
    for s in range(4):
        init[idx(s, 0)] = Fr(1, 4)
    name = f"{'generic' if generic else 'twisted'}_square_{m}"
    return hmm_from_edges(name, 4 * m, 4, edges, init=init)


def action_process(name: str, maps: Sequence[Sequence[int]]) -> GHMM:
    """A unifilar HMM whose hidden state is a point moved by the observed symbol.

    Two symbols.  Symbol a sends point x to maps[a][x].  From point x, symbol
    0 has probability 1/10 + (8/10) x / (n - 1), so the next-symbol law
    differs between points and every word is possible.  The start point is 0
    and every point must be reachable.  The predictive states are then the
    points, and S_p is the monoid generated by the maps (Project A.2).
    """
    n, k = len(maps[0]), len(maps)
    assert k == 2
    edges = []
    for x in range(n):
        p0 = Fr(1, 10) + Fr(8, 10) * Fr(x, n - 1)
        edges += [(x, 0, maps[0][x], p0), (x, 1, maps[1][x], 1 - p0)]
    return hmm_from_edges(name, n, k, edges, init=[1] + [0] * (n - 1))


def _cycles(n: int, *cycles) -> list:
    m = list(range(n))
    for c in cycles:
        for i, x in enumerate(c):
            m[x] = c[(i + 1) % len(c)]
    return m


# Project A.2: hidden dynamics driven by a chosen monoid, two generators each
ACTIONS = {
    "act_s3": [_cycles(3, (0, 1)), _cycles(3, (0, 1, 2))],             # S_3 on 3 points
    "act_z6": [[(x + 3) % 6 for x in range(6)], [(x + 2) % 6 for x in range(6)]],  # Z_2 x Z_3
    "act_s4": [_cycles(4, (0, 1)), _cycles(4, (0, 1, 2, 3))],          # S_4 on 4 points, solvable
    "act_a5": [_cycles(5, (0, 1, 2)), _cycles(5, (0, 1, 2, 3, 4))],    # A_5 on 5 points, non-solvable
    "act_ap5": [[min(x + 1, 4) for x in range(5)], [max(x - 1, 0) for x in range(5)]],  # aperiodic
    # aperiodic with no synchronising word: points 0, 1 are transient, then the process is
    # latched into {2, 3} or {4, 5} for good, and inside either pair the last symbol is the point
    "act_latch": [[1, 2, 2, 2, 4, 4], [0, 4, 3, 3, 5, 5]],
    # the same with more to remember: two symbols after the first 0 pick one of four pairs
    # (minimum rank 4), and one symbol picks one of two clamped walks on 4 points (minimum rank 2)
    "act_latch4": [[1, 2, 4, 8, 4, 4, 6, 6, 8, 8, 10, 10], [0, 3, 6, 10, 5, 5, 7, 7, 9, 9, 11, 11]],
    "act_latchwalk": [[1, 2, 3, 4, 5, 5, 7, 8, 9, 9], [0, 6, 2, 2, 3, 4, 6, 6, 7, 8]],
}


REGISTRY = {
    **{name: (lambda name=name: action_process(name, ACTIONS[name])) for name in ACTIONS},
    "iid": iid,
    "z1r": z1r,
    "rrxor": rrxor,
    "reset_chain": reset_chain,
    "square_chain": square_chain,
    "mod3": lambda: mod_counter(3),
    "mod5": lambda: mod_counter(5),
    "mod7": lambda: mod_counter(7),
    "count3": lambda: mod_counter(3, 2),
    "count5": lambda: mod_counter(5, 2),
    # matched families for the d-sweep: ternary (t) and binary (b) alphabets
    **{f"t{m}": (lambda m=m: mod_counter(m, 3)) for m in (3, 5, 7, 11)},
    **{f"b{m}": (lambda m=m: mod_counter(m, 2)) for m in (3, 5, 7, 9)},
    # matched pair for d against n: same n = 12, with d = 9 and d = 12
    "tw3": lambda: twisted_square(3),
    "gen3": lambda: twisted_square(3, generic=True),
}


def get(name: str) -> GHMM:
    return REGISTRY[name]()
